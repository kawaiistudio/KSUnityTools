    /// The Kawaii Studio material inspector for the shaders that have no hand-written one
    /// (KSScreenShader, VR Stereo Display, KSVideoDecoder, screen overlay). Same look as the
    /// hand-written inspectors (BloodKiller, Vampire Eye, Hair): branded banner, coloured
    /// collapsible sections, community footer -- but the sections come from the shader itself:
    /// every [Header(...)] attribute in its Properties block opens one, properties before the
    /// first header land in "Settings", [HideInInspector] ones stay hidden, and the property
