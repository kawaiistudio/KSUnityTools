        private sealed class Section
        {
            public string Title;
            public List<MaterialProperty> Props = new List<MaterialProperty>();
        }

        public override void OnGUI(MaterialEditor materialEditor, MaterialProperty[] properties)
        {
            var material = materialEditor.target as Material;
            Shader shader = material != null ? material.shader : null;
            Profile profile = shader != null && Profiles.TryGetValue(shader.name, out var p) ? p : Fallback;
            if (_logo == null) _logo = KawaiiStudio.KawaiiStudioBranding.Logo;
            if (_banner == null) _banner = KawaiiStudio.KawaiiStudioBranding.Banner;

            DrawBanner(profile);
            if (!string.IsNullOrEmpty(profile.Hint))
            {
                EditorGUILayout.Space(6);
                EditorGUILayout.HelpBox(profile.Hint, MessageType.None);
            }
            EditorGUILayout.Space(8);

            List<MaterialProperty> atlas;
            var sections = BuildSections(shader, properties, profile, out atlas);
            string key = shader != null ? shader.name : "?";
            int index = 0;
            foreach (var section in sections)
            {
                Color accent = index == 0 ? profile.Accent : Color.Lerp(profile.Accent, Color.white, 0.12f * (index % 4));
                DrawSection(key + "/" + section.Title, section.Title, accent, () =>
                {
                    foreach (var prop in section.Props) DrawProperty(materialEditor, prop, profile);
                });
                index++;
            }
            if (atlas != null && atlas.Count > 0) DrawAtlas(key, materialEditor, atlas, profile);

            EditorGUILayout.Space(10);
            DrawSection(key + "/__render", "RENDERING", new Color(0.5f, 0.5f, 0.5f), () =>
            {
                materialEditor.RenderQueueField();
                materialEditor.EnableInstancingField();
                materialEditor.DoubleSidedGIField();
            }, defaultOpen: false);

            EditorGUILayout.Space(15);
            DrawFooter(profile);
        }

        // ------------------------------------------------------------------ sections from the shader

        private static List<Section> BuildSections(Shader shader, MaterialProperty[] properties, Profile profile, out List<MaterialProperty> atlas)
        {
            var sections = new List<Section>();
            atlas = profile.AtlasPrefix != null ? new List<MaterialProperty>() : null;
            var current = new Section { Title = "SETTINGS" };
            sections.Add(current);

            for (int i = 0; i < properties.Length; i++)
            {
                MaterialProperty prop = properties[i];
                if ((prop.flags & MaterialProperty.PropFlags.HideInInspector) != 0) continue;

                // a [Header(X)] on this property opens a new section
                string header = HeaderOf(shader, prop.name);
                if (header != null)
                {
                    if (current.Props.Count == 0) current.Title = header;    // "SETTINGS" was never used: rename it
                    else { current = new Section { Title = header }; sections.Add(current); }
                }

                if (atlas != null && IsAtlasSlot(prop, profile.AtlasPrefix)) { atlas.Add(prop); continue; }
                current.Props.Add(prop);
            }
            sections.RemoveAll(s => s.Props.Count == 0);
            return sections;
        }

        private static readonly Dictionary<string, Dictionary<string, string>> HeaderCache = new Dictionary<string, Dictionary<string, string>>();

        /// <summary>The text of the [Header(...)] attribute declared on a property, or null.</summary>
        private static string HeaderOf(Shader shader, string propertyName)
        {
            if (shader == null) return null;
            if (!HeaderCache.TryGetValue(shader.name, out var map))
            {
                map = new Dictionary<string, string>();
                int n = shader.GetPropertyCount();
                for (int i = 0; i < n; i++)
                {
                    foreach (string attr in shader.GetPropertyAttributes(i))
                    {
                        // "Header(MAIN SETTINGS)" -> "MAIN SETTINGS"
                        if (attr.StartsWith("Header(", StringComparison.Ordinal) && attr.EndsWith(")", StringComparison.Ordinal))
                        {
                            map[shader.GetPropertyName(i)] = attr.Substring(7, attr.Length - 8).Trim().ToUpperInvariant();
                            break;
                        }
                    }
                }
                HeaderCache[shader.name] = map;
            }
            return map.TryGetValue(propertyName, out var h) ? h : null;
        }

        private static bool IsAtlasSlot(MaterialProperty prop, string prefix)
        {
            if (prop.type != MaterialProperty.PropType.Texture || !prop.name.StartsWith(prefix, StringComparison.Ordinal)) return false;
            string rest = prop.name.Substring(prefix.Length);
            return rest.Length == 0 || int.TryParse(rest, out _);
        }

        // ------------------------------------------------------------------ drawing

        private static void DrawProperty(MaterialEditor editor, MaterialProperty prop, Profile profile)
        {
            EditorGUILayout.BeginHorizontal();
            GUILayout.Space(10);
            if (profile.Popups != null && profile.Popups.TryGetValue(prop.name, out string[] options) && prop.type == MaterialProperty.PropType.Float)
            {
                EditorGUI.showMixedValue = prop.hasMixedValue;
                EditorGUI.BeginChangeCheck();
                int value = EditorGUILayout.Popup(prop.displayName, Mathf.Clamp(Mathf.RoundToInt(prop.floatValue), 0, options.Length - 1), options);
                if (EditorGUI.EndChangeCheck()) prop.floatValue = value;
                EditorGUI.showMixedValue = false;
            }
            else
            {
                editor.ShaderProperty(prop, prop.displayName);
            }
            EditorGUILayout.EndHorizontal();
        }

        private static void DrawAtlas(string key, MaterialEditor editor, List<MaterialProperty> atlas, Profile profile)
        {
            int used = 0;
            foreach (var p in atlas) if (p.textureValue != null) used++;
            DrawSection(key + "/__atlas", $"ATLAS TEXTURES  ({used} of {atlas.Count} used)", profile.Accent, () =>
            {
                EditorGUILayout.LabelField("Filled by the Video Animator. Empty slots after the last used one are hidden.", EditorStyles.miniLabel);
                // every used slot, then the first empty one (to add by hand)
                bool shownEmpty = false;
                foreach (var p in atlas)
                {
                    bool empty = p.textureValue == null;
                    if (empty && shownEmpty) continue;
                    if (empty) shownEmpty = true;
                    EditorGUILayout.BeginHorizontal();
                    GUILayout.Space(10);
                    editor.TexturePropertySingleLine(new GUIContent(p.displayName), p);
                    EditorGUILayout.EndHorizontal();
                }
            }, defaultOpen: used > 0);
        }

        private static void DrawBanner(Profile profile)
        {
            Rect bannerRect = GUILayoutUtility.GetRect(0, 120, GUILayout.ExpandWidth(true));
            Color dark = Color.Lerp(profile.Accent, Color.black, 0.72f);
            DrawGradientRect(bannerRect, DeepBlack, dark);
            DrawBorder(bannerRect, profile.Accent, 3);
            Rect innerRect = new Rect(bannerRect.x + 5, bannerRect.y + 5, bannerRect.width - 10, bannerRect.height - 10);
            DrawBorder(innerRect, new Color(profile.Accent.r, profile.Accent.g, profile.Accent.b, 0.3f), 1);

            if (_banner != null)
            {
                float aspect = (float)_banner.width / _banner.height;
                float w = Mathf.Min(bannerRect.width - 20, 300);
                Rect texRect = new Rect(bannerRect.x + (bannerRect.width - w) / 2, bannerRect.y + 10, w, Mathf.Min(w / aspect, bannerRect.height - 20));
                GUI.DrawTexture(texRect, _banner, ScaleMode.ScaleToFit);
            }
            if (_logo != null)
            {
                const float logoSize = 60;
                Rect logoRect = new Rect(bannerRect.x + 15, bannerRect.y + (bannerRect.height - logoSize) / 2, logoSize, logoSize);
                GUI.color = new Color(0, 0, 0, 0.5f);
                GUI.DrawTexture(new Rect(logoRect.x + 2, logoRect.y + 2, logoRect.width, logoRect.height), _logo);
                GUI.color = Color.white;
                GUI.DrawTexture(logoRect, _logo, ScaleMode.ScaleToFit);
            }

            var titleStyle = new GUIStyle(EditorStyles.boldLabel)
            {
                fontSize = 22, alignment = TextAnchor.MiddleRight, normal = { textColor = Color.white }, padding = new RectOffset(0, 20, 0, 0),
            };
            GUI.Label(new Rect(bannerRect.x, bannerRect.y + 25, bannerRect.width, 30), profile.Title, titleStyle);
            var subtitleStyle = new GUIStyle(EditorStyles.label)
            {
                fontSize = 11, alignment = TextAnchor.MiddleRight, normal = { textColor = Color.Lerp(profile.Accent, Color.white, 0.5f) }, padding = new RectOffset(0, 20, 0, 0),
            };
            GUI.Label(new Rect(bannerRect.x, bannerRect.y + 50, bannerRect.width, 20), profile.Subtitle, subtitleStyle);

            Rect versionRect = new Rect(bannerRect.x + bannerRect.width - 70, bannerRect.y + bannerRect.height - 25, 60, 18);
            EditorGUI.DrawRect(versionRect, new Color(profile.Accent.r, profile.Accent.g, profile.Accent.b, 0.8f));
            GUI.Label(versionRect, "v" + KawaiiStudio.KawaiiStudioVersion.Current, new GUIStyle(EditorStyles.miniLabel)
            {
                alignment = TextAnchor.MiddleCenter, normal = { textColor = Color.white }, fontStyle = FontStyle.Bold,
            });
        }

        private static void DrawSection(string key, string title, Color accent, Action content, bool defaultOpen = true)
        {
            if (!Foldouts.TryGetValue(key, out bool open)) open = defaultOpen;
            EditorGUILayout.Space(3);
            Rect headerRect = GUILayoutUtility.GetRect(0, 28, GUILayout.ExpandWidth(true));
            EditorGUI.DrawRect(headerRect, open ? new Color(accent.r * 0.3f, accent.g * 0.3f, accent.b * 0.3f) : SectionBg);
            EditorGUI.DrawRect(new Rect(headerRect.x, headerRect.y, 4, headerRect.height), accent);
            GUI.Label(new Rect(headerRect.x + 10, headerRect.y, 20, headerRect.height), open ? "▼" : "▶",
                new GUIStyle(EditorStyles.label) { normal = { textColor = accent }, fontSize = 10, alignment = TextAnchor.MiddleLeft });
            GUI.Label(headerRect, title, new GUIStyle(EditorStyles.boldLabel)
            {
                fontSize = 12, alignment = TextAnchor.MiddleLeft, normal = { textColor = Color.white }, padding = new RectOffset(30, 0, 0, 0),
            });
            if (GUI.Button(headerRect, "", GUIStyle.none)) { open = !open; Foldouts[key] = open; }
            EditorGUIUtility.AddCursorRect(headerRect, MouseCursor.Link);

            if (!open) return;
            Rect contentRect = EditorGUILayout.BeginVertical();
            EditorGUI.DrawRect(new Rect(contentRect.x, contentRect.y, 2, contentRect.height), new Color(accent.r, accent.g, accent.b, 0.3f));
            EditorGUILayout.Space(5);
            EditorGUI.indentLevel++;
            content();
            EditorGUI.indentLevel--;
            EditorGUILayout.Space(5);
            EditorGUILayout.EndVertical();
        }

        private static void DrawFooter(Profile profile)
        {
            Rect sep = GUILayoutUtility.GetRect(0, 2, GUILayout.ExpandWidth(true));
            DrawGradientRect(sep, Color.Lerp(profile.Accent, Color.black, 0.6f), profile.Accent);
            EditorGUILayout.Space(10);

            EditorGUILayout.BeginHorizontal();
            GUILayout.FlexibleSpace();
            DrawSocialButton("Discord", DISCORD_URL, new Color(0.34f, 0.4f, 0.95f));
            GUILayout.Space(5);
            DrawSocialButton("Telegram", TELEGRAM_URL, new Color(0.16f, 0.63f, 0.89f));
            GUILayout.Space(5);
            DrawSocialButton("VRChat", VRCHAT_URL, new Color(0.07f, 0.71f, 0.65f));
            GUILayout.Space(5);
            DrawSocialButton("GitHub", GITHUB_URL, new Color(0.9f, 0.9f, 0.9f));
            GUILayout.FlexibleSpace();
            EditorGUILayout.EndHorizontal();

            EditorGUILayout.Space(10);
            var credit = new GUIStyle(EditorStyles.centeredGreyMiniLabel) { fontSize = 10, normal = { textColor = new Color(0.6f, 0.6f, 0.6f) } };
            EditorGUILayout.LabelField("Made with ❤️ by Kawaii Studio", credit);
            EditorGUILayout.LabelField("Join our community!", credit);
            EditorGUILayout.Space(5);
        }

        private static void DrawSocialButton(string label, string url, Color color)
        {
            var style = new GUIStyle(GUI.skin.button)
            {
                fixedHeight = 25, fixedWidth = 70, fontSize = 10, fontStyle = FontStyle.Bold,
                normal = { textColor = Color.white }, hover = { textColor = Color.white },
            };
            Color old = GUI.backgroundColor;
            GUI.backgroundColor = color;
            if (GUILayout.Button(label, style)) Application.OpenURL(url);
            GUI.backgroundColor = old;
        }

        private static void DrawGradientRect(Rect rect, Color left, Color right)
        {
            const int steps = 20;
            float stepWidth = rect.width / steps;
            for (int i = 0; i < steps; i++)
                EditorGUI.DrawRect(new Rect(rect.x + i * stepWidth, rect.y, stepWidth + 1, rect.height), Color.Lerp(left, right, (float)i / steps));
        }

        private static void DrawBorder(Rect rect, Color color, int thickness)
        {
            EditorGUI.DrawRect(new Rect(rect.x, rect.y, rect.width, thickness), color);
            EditorGUI.DrawRect(new Rect(rect.x, rect.y + rect.height - thickness, rect.width, thickness), color);
            EditorGUI.DrawRect(new Rect(rect.x, rect.y, thickness, rect.height), color);
            EditorGUI.DrawRect(new Rect(rect.x + rect.width - thickness, rect.y, thickness, rect.height), color);
        }
